/**
 * Escapes unsafe HTML characters to prevent XSS in email bodies or rendered logs.
 */
export function sanitizeHtml(str: string): string {
  if (!str) return ''
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;')
}
